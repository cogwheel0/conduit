// Regenerates conduit_core's table of Open WebUI's emoji shortcodes from the
// list Open WebUI ships (`src/lib/emoji-shortcodes.json` in the
// openwebui-src submodule).
//
//   dart run tool/generate_emoji_shortcodes.dart
//
// Writes packages/conduit_core/lib/utils/emoji_shortcode_table.dart: one
// ASCII string of `CODEPOINTS:name,name;...` entries, which
// `emojiForShortcode` reads into a map the first time it is used. A single
// one-byte string keeps the table small in the app (about 40 KB) next to a
// const map of some 2,000 string pairs.
import 'dart:convert';
import 'dart:io';

const _source = 'openwebui-src/src/lib/emoji-shortcodes.json';
const _output = 'packages/conduit_core/lib/utils/emoji_shortcode_table.dart';

/// Longest line the generated string literals may make, with indent and
/// quotes.
const _maxLineLength = 80;

final _shortcodePattern = RegExp(r'^[a-z0-9_+-]+$');
final _codePointsPattern = RegExp(r'^[0-9A-F]+(-[0-9A-F]+)*$');

void main() {
  final source = File(_source);
  if (!source.existsSync()) {
    stderr.writeln(
      'Missing $_source. Run `git submodule update --init openwebui-src`.',
    );
    exit(1);
  }
  final decoded = jsonDecode(source.readAsStringSync()) as Map<String, Object?>;

  final entries = <String>[];
  final seen = <String>{};
  for (final MapEntry(:key, :value) in decoded.entries) {
    final codePoints = key.toUpperCase();
    if (!_codePointsPattern.hasMatch(codePoints)) {
      throw FormatException('Unexpected code points', key);
    }
    final names = switch (value) {
      final String name => [name],
      final List<Object?> names => names.cast<String>(),
      _ => throw FormatException('Unexpected shortcodes for $key', value),
    };
    for (final name in names) {
      if (!_shortcodePattern.hasMatch(name)) {
        throw FormatException('Unexpected shortcode', name);
      }
      if (!seen.add(name)) {
        throw FormatException('Shortcode named twice', name);
      }
    }
    entries.add('$codePoints:${names.join(',')}');
  }

  // Adjacent string literals, broken after an entry where one ends within
  // the line, so the file stays readable and within the line length. Room
  // for four spaces of indent, two quotes and the closing semicolon.
  const room = _maxLineLength - 7;
  final table = entries.join(';');
  final lines = <String>[];
  var start = 0;
  while (start < table.length) {
    var end = start + room;
    if (end >= table.length) {
      end = table.length;
    } else {
      final lastBreak = table.lastIndexOf(';', end - 1);
      if (lastBreak >= start) end = lastBreak + 1;
    }
    lines.add(table.substring(start, end));
    start = end;
  }

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_emoji_shortcodes.dart from Open')
    ..writeln("// WebUI's src/lib/emoji-shortcodes.json. Do not edit by hand.")
    ..writeln()
    ..writeln("/// Open WebUI's emoji shortcodes: `;`-separated entries of an")
    ..writeln("/// emoji's code points in hex, joined by `-`, then `:` and the")
    ..writeln('/// shortcodes that name it, joined by `,`. Read it through')
    ..writeln('/// `emojiForShortcode`.')
    ..writeln('const String openWebUiEmojiShortcodeTable =');
  for (var index = 0; index < lines.length; index++) {
    final end = index == lines.length - 1 ? ';' : '';
    out.writeln("    '${lines[index]}'$end");
  }
  File(_output).writeAsStringSync(out.toString());
  stdout.writeln(
    'Wrote $_output: ${entries.length} emoji, ${seen.length} shortcodes.',
  );
}
