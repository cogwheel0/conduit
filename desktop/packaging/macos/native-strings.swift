// Writes `<lang>.lproj/<table>` .strings files from the app's ARB catalogs
// (lib/l10n/app_*.arb and lib/l10n/desktop/desktop_*.arb), for the parts of
// the bundle macOS reads itself: the Services menu titles
// (ServicesMenu.strings) and the Share extension's sheet
// (Localizable.strings). The ARB files stay the one source of every string.
//
//   xcrun swift native-strings.swift L10N_DIR OUT_DIR TABLE KEY=ARB_KEY[%] ...
//
// KEY is the .strings key; ARB_KEY the catalog key. A trailing % marks a
// format string: `{name}` placeholders become `%1$@`, `%2$@` … in the
// English text's order, and a literal % becomes %%. Plurals and selects are
// refused (a .strings table cannot hold them). A key a locale lacks takes
// the English text, as the app does.

import Foundation

struct Entry {
  let key: String
  let arbKey: String
  let format: Bool
}

func fail(_ message: String) -> Never {
  FileHandle.standardError.write(Data("native-strings: \(message)\n".utf8))
  exit(1)
}

let args = CommandLine.arguments
guard args.count >= 5 else {
  fail("usage: native-strings.swift L10N_DIR OUT_DIR TABLE KEY=ARB_KEY[%] ...")
}
let l10nDir = URL(fileURLWithPath: args[1], isDirectory: true)
let outDir = URL(fileURLWithPath: args[2], isDirectory: true)
let table = args[3]
let entries: [Entry] = args[4...].map { spec in
  guard let eq = spec.lastIndex(of: "=") else { fail("not KEY=ARB_KEY: \(spec)") }
  var arbKey = String(spec[spec.index(after: eq)...])
  let format = arbKey.hasSuffix("%")
  if format { arbKey.removeLast() }
  return Entry(key: String(spec[..<eq]), arbKey: arbKey, format: format)
}

func catalog(_ url: URL) -> [String: String] {
  guard let data = try? Data(contentsOf: url) else { return [:] }
  guard let json = try? JSONSerialization.jsonObject(with: data) as? [String: Any] else {
    fail("not a JSON object: \(url.path)")
  }
  var out: [String: String] = [:]
  for (key, value) in json where !key.hasPrefix("@") {
    if let text = value as? String { out[key] = text }
  }
  return out
}

func messages(for locale: String) -> [String: String] {
  var merged = catalog(l10nDir.appendingPathComponent("app_\(locale).arb"))
  for (key, value) in catalog(l10nDir.appendingPathComponent("desktop/desktop_\(locale).arb")) {
    merged[key] = value
  }
  return merged
}

/// `{name}` placeholders in order of first use.
func placeholders(_ message: String) -> [String] {
  var names: [String] = []
  var rest = Substring(message)
  while let open = rest.firstIndex(of: "{") {
    guard let close = rest[open...].firstIndex(of: "}") else { break }
    let inside = rest[rest.index(after: open)..<close]
    if inside.contains(",") { fail("plural or select in a native string: \(message)") }
    let name = String(inside)
    if !names.contains(name) { names.append(name) }
    rest = rest[rest.index(after: close)...]
  }
  return names
}

func formatted(_ message: String, order: [String]) -> String {
  var text = message.replacingOccurrences(of: "%", with: "%%")
  for (index, name) in order.enumerated() {
    text = text.replacingOccurrences(of: "{\(name)}", with: "%\(index + 1)$@")
  }
  if text.contains("{") { fail("a placeholder the English text lacks: \(message)") }
  return text
}

func escaped(_ text: String) -> String {
  text.replacingOccurrences(of: "\\", with: "\\\\")
    .replacingOccurrences(of: "\"", with: "\\\"")
    .replacingOccurrences(of: "\n", with: "\\n")
}

func lproj(_ locale: String) -> String {
  switch locale {
  case "zh": return "zh-Hans"
  case "zh_Hant": return "zh-Hant"
  default: return locale.replacingOccurrences(of: "_", with: "-")
  }
}

let fileManager = FileManager.default
guard let names = try? fileManager.contentsOfDirectory(atPath: l10nDir.path) else {
  fail("no folder \(l10nDir.path)")
}
let locales = names.compactMap { name -> String? in
  guard name.hasPrefix("app_"), name.hasSuffix(".arb") else { return nil }
  return String(name.dropFirst(4).dropLast(4))
}.sorted()
guard locales.contains("en") else { fail("no app_en.arb in \(l10nDir.path)") }

let english = messages(for: "en")
for entry in entries where english[entry.arbKey] == nil {
  fail("no English text for \(entry.arbKey)")
}

for locale in locales {
  let catalog = messages(for: locale)
  var lines = ["/* Generated by desktop/packaging/macos/native-strings.swift from lib/l10n. */"]
  for entry in entries {
    var value = catalog[entry.arbKey] ?? english[entry.arbKey]!
    if entry.format {
      value = formatted(value, order: placeholders(english[entry.arbKey]!))
    } else if value.contains("{") {
      fail("\(entry.arbKey) has placeholders: mark it with %")
    }
    lines.append("\"\(escaped(entry.key))\" = \"\(escaped(value))\";")
  }
  let folder = outDir.appendingPathComponent("\(lproj(locale)).lproj", isDirectory: true)
  do {
    try fileManager.createDirectory(at: folder, withIntermediateDirectories: true)
    try (lines.joined(separator: "\n") + "\n").write(
      to: folder.appendingPathComponent(table), atomically: true, encoding: .utf8)
  } catch {
    fail("could not write \(folder.path)/\(table): \(error)")
  }
}
print("native-strings: \(table) in \(locales.count) languages")
