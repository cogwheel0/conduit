//! `notes/keyboard.md` (from the running app: its keymap, key bindings and
//! menus, plus what the run saw: real menus' items, focus orders, tooltips),
//! `notes/inventory.json` and `notes/run.json` (missing states, problems,
//! motion stats).

use std::fmt::Write as _;

use gpui_kit::{App, AsyncApp, OperatingSystem, OwnedMenuItem};
use serde_json::json;

use super::{Run, inventory_json};
use crate::AppState;
use crate::l10n::ActiveL10n as _;

/// A binding as a Mac menu writes it: modifiers in Apple's order (⌃⌥⇧⌘).
fn chord(binding: &gpui_kit::KeyBinding) -> String {
    binding
        .keystrokes()
        .iter()
        .map(|k| {
            let ks = gpui_kit::Keystroke {
                modifiers: *k.modifiers(),
                key: k.key().to_string(),
                key_char: None,
            };
            crate::keymap::from_gpui(&ks)
                .map(|s| crate::keymap::describe(&s, true))
                .unwrap_or_else(|| k.display(OperatingSystem::Mac).to_string())
        })
        .collect::<Vec<_>>()
        .join(" ")
}

/// The shortcut a menu item shows: GPUI's macOS menus take the first
/// binding that applies anywhere, else the first at all.
fn shortcut_for(action: &dyn gpui_kit::Action, cx: &App) -> Option<String> {
    let keymap = cx.key_bindings();
    let keymap = keymap.borrow();
    let bindings: Vec<_> = keymap.bindings_for_action(action).collect();
    bindings
        .iter()
        .find(|b| b.predicate().is_none())
        .or(bindings.first())
        .map(|b| chord(b))
}

fn menu_items(items: &[OwnedMenuItem], depth: usize, out: &mut String, cx: &App) {
    let indent = "  ".repeat(depth);
    for item in items {
        match item {
            OwnedMenuItem::Separator => {
                let _ = writeln!(out, "{indent}- \u{2014}");
            }
            OwnedMenuItem::Submenu(menu) => {
                let _ = writeln!(out, "{indent}- {} \u{25b8}", menu.name);
                menu_items(&menu.items, depth + 1, out, cx);
            }
            OwnedMenuItem::SystemMenu(menu) => {
                let _ = writeln!(out, "{indent}- {} \u{25b8} (system)", menu.name);
            }
            OwnedMenuItem::Action {
                name,
                action,
                disabled,
                checked,
                ..
            } => {
                let key = shortcut_for(action.as_ref(), cx)
                    .map(|k| format!("  `{k}`"))
                    .unwrap_or_default();
                let mut line = format!(
                    "{indent}- {}{name}{key}",
                    if *checked { "\u{2713} " } else { "" }
                );
                if *disabled {
                    line.push_str(" (disabled)");
                }
                let _ = writeln!(out, "{line}  \u{2192} {}", action.name());
            }
        }
    }
}

fn keyboard_md(run: &Run, cx: &mut App) -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "# Keyboard, menus and focus\n\nGenerated by `--capture` from the running app (its keymap, key bindings and menus) and from what the run saw (the real menus' items, focus as Tab and arrows moved it, tooltips on hover). English, macOS, with System Settings \u{203a} Keyboard \u{203a} Keyboard Navigation on (Tab reaches every control).\n"
    );

    // The rebindable table.
    let l10n = cx.l10n().clone();
    let keymap = cx.global::<AppState>().settings.read(cx).keymap();
    let _ = writeln!(
        out,
        "## Shortcuts (Settings \u{203a} Keyboard)\n\n| Action | Shortcut | Bound now | Works while typing |\n| --- | --- | --- | --- |"
    );
    // Settings lists only what the app can carry out.
    for s in keymap.table().into_iter().filter(|s| s.action.is_live()) {
        let _ = writeln!(
            out,
            "| {} | `{}` | {} | {} |",
            crate::views::settings::shortcut_label(s.action, &l10n),
            crate::keymap::describe(&s.stroke, true),
            if s.action.is_live() && s.while_typing {
                "yes"
            } else {
                "no (not available yet)"
            },
            if s.while_typing { "yes" } else { "no" },
        );
    }

    // The menu bar.
    let _ = writeln!(out, "\n## Menu bar (as the app installs it)\n");
    for menu in cx.get_menus().unwrap_or_default() {
        let _ = writeln!(out, "### {}\n", menu.name);
        menu_items(&menu.items, 0, &mut out, cx);
        let _ = writeln!(out);
    }

    // Menus as AppKit showed them.
    let _ = writeln!(
        out,
        "## Menus as shown (read from the real NSMenus when they opened)\n\nTitle, a check when on, `[shortcut]`, (disabled), \u{25b8} for a submenu, \u{2014} for a separator.\n"
    );
    for (name, items, real) in &run.notes.menus {
        let _ = writeln!(
            out,
            "### {name}{}\n",
            if *real { "" } else { " (from the code)" }
        );
        if items.is_empty() {
            let _ = writeln!(out, "- (no items recorded)");
        }
        for i in items {
            let _ = writeln!(out, "- {i}");
        }
        let _ = writeln!(out);
    }

    // Focus.
    let _ = writeln!(
        out,
        "## Keyboard focus, step by step\n\nEach step is one key press from the starting point; `interaction/NN-focus-<screen>-step-NN.png` shows it. \u{201c}Back to the first stop\u{201d} means the cycle closed there.\n"
    );
    for (screen, order) in &run.notes.focus {
        let _ = writeln!(out, "### {screen}\n");
        for (i, stop) in order.iter().enumerate() {
            let _ = writeln!(out, "{}. {stop}", i + 1);
        }
        let _ = writeln!(out);
    }

    // Tooltips.
    let shown = run.notes.tooltips.iter().filter(|t| t.2).count();
    let _ = writeln!(
        out,
        "## Icon-only buttons and tooltips\n\nEach icon-only button (a square control up to 40 pt) was hovered for 1.3 s; a tooltip counts when something appeared outside the button. {shown} of {} show one.\n\n| Screen | Button (accessibility label) | Tooltip | Shot |\n| --- | --- | --- | --- |",
        run.notes.tooltips.len()
    );
    for (screen, label, has, file) in &run.notes.tooltips {
        let _ = writeln!(
            out,
            "| {screen} | {label} | {} | `interaction/{file}` |",
            if *has { "yes" } else { "**none**" }
        );
    }
    // Everything bound, by context.
    let _ = writeln!(
        out,
        "\n## Appendix: every key binding, by context\n\nThe app's own (`conduit::*`) and GPUI Kit's (text fields, lists, menus).\n"
    );
    let mut rows: Vec<(String, String, String)> = vec![];
    {
        let bindings = cx.key_bindings();
        let bindings = bindings.borrow();
        for b in bindings.bindings() {
            let context = b
                .predicate()
                .map(|p| p.to_string())
                .unwrap_or_else(|| "(anywhere)".into());
            rows.push((context, chord(b), b.action().name().to_string()));
        }
    }
    rows.sort();
    rows.dedup();
    let mut last = String::new();
    for (context, keys, action) in rows {
        if context != last {
            let _ = writeln!(out, "\n**{context}**\n");
            last = context.clone();
        }
        let _ = writeln!(out, "- `{keys}` \u{2192} {action}");
    }

    out
}

pub async fn write(run: &mut Run, cx: &mut AsyncApp) {
    let md = cx.update(|cx| keyboard_md(run, cx));
    std::fs::write(run.path("notes", "keyboard.md"), md).ok();
    let inventory = serde_json::to_vec_pretty(&inventory_json(&run.inventory)).unwrap_or_default();
    std::fs::write(run.path("notes", "inventory.json"), inventory).ok();
    let summary = json!({
        "missing": run.notes.missing.iter().map(|(s, r)| json!({"state": s, "reason": r})).collect::<Vec<_>>(),
        "problems": run.notes.problems,
        "motion": run.notes.motion,
        "focus": run.notes.focus.iter().map(|(s, o)| json!({"screen": s, "order": o})).collect::<Vec<_>>(),
        "tooltips": run.notes.tooltips.iter().map(|(s, l, h, f)| json!({"screen": s, "label": l, "tooltip": h, "file": f})).collect::<Vec<_>>(),
    });
    std::fs::write(
        run.path("notes", "run.json"),
        serde_json::to_vec_pretty(&summary).unwrap_or_default(),
    )
    .ok();
}
