//! Generates typed l10n accessors from the shared ARB catalogs:
//! `lib/l10n/app_*.arb` (the mobile app's strings) and
//! `lib/l10n/desktop/desktop_*.arb` (desktop-only strings), 14 locales.
//!
//! Output (`$OUT_DIR/l10n_generated.rs`):
//! * `LOCALES`, with `en` (the template) first;
//! * `KEYS` and per-key placeholder names, for the completeness tests;
//! * one message table per locale (`None` where a locale lacks a key, which
//!   falls back to English at run time);
//! * `impl L10n { pub fn <snake_key>(&self, <typed placeholders>) -> String }`
//!   for every key, documented with its English text.
//!
//! Messages stay ICU strings; `src/l10n/icu.rs` formats them (placeholders,
//! `plural` with `=n`/CLDR categories/`#`, and `select`).
//!
//! On macOS it also compiles the App Intents' Swift ([`app_intents`]) and the
//! Swift engine for Apple's on-device model ([`apple_models`]), both linked
//! against the system's Swift runtime ([`swift_runtime`]).

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use serde_json::{Map, Value};

#[allow(dead_code)]
#[path = "src/l10n/icu.rs"]
mod icu;

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    app_intents(&manifest);
    apple_models(&manifest);
    swift_runtime();
    let l10n = manifest.join("../../../lib/l10n");
    let desktop = l10n.join("desktop");
    println!("cargo:rerun-if-changed={}", l10n.display());
    println!("cargo:rerun-if-changed={}", desktop.display());

    // locale -> key -> message
    let mut catalogs: BTreeMap<String, BTreeMap<String, String>> = BTreeMap::new();
    // key -> declared placeholders (name, type), from the English template
    let mut declared: BTreeMap<String, Vec<(String, String)>> = BTreeMap::new();
    let mut desktop_keys = BTreeSet::new();
    for (dir, prefix) in [(&l10n, "app_"), (&desktop, "desktop_")] {
        for (locale, path) in arb_files(dir, prefix) {
            println!("cargo:rerun-if-changed={}", path.display());
            let text = std::fs::read_to_string(&path).unwrap();
            let json: Map<String, Value> =
                serde_json::from_str(&text).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
            let catalog = catalogs.entry(locale.clone()).or_default();
            for (key, value) in &json {
                if key.starts_with('@') {
                    continue;
                }
                let Some(message) = value.as_str() else {
                    continue;
                };
                if prefix == "desktop_" && locale == "en" {
                    desktop_keys.insert(key.clone());
                }
                if let Some(prev) = catalog.insert(key.clone(), message.to_string())
                    && prev != message
                {
                    panic!("{key} ({locale}) is defined differently in the app and desktop ARBs");
                }
                if locale == "en" {
                    let mut names = vec![];
                    if let Some(ph) = json
                        .get(&format!("@{key}"))
                        .and_then(|m| m.get("placeholders"))
                        .and_then(Value::as_object)
                    {
                        for (name, meta) in ph {
                            let ty = meta
                                .get("type")
                                .and_then(Value::as_str)
                                .unwrap_or("String")
                                .to_string();
                            names.push((name.clone(), ty));
                        }
                    }
                    declared.insert(key.clone(), names);
                }
            }
        }
    }
    let en = catalogs
        .get("en")
        .expect("app_en.arb is the template")
        .clone();
    let mut locales: Vec<String> = catalogs.keys().cloned().collect();
    locales.retain(|l| l != "en");
    locales.insert(0, "en".into());

    let keys: Vec<String> = en.keys().cloned().collect();
    let mut out = String::new();
    writeln!(
        out,
        "// @generated by crates/app/build.rs from lib/l10n. Do not edit."
    )
    .unwrap();
    writeln!(out, "pub const LOCALES: &[&str] = &{:?};", locales).unwrap();
    writeln!(out, "pub const KEY_COUNT: usize = {};", keys.len()).unwrap();
    writeln!(out, "pub const KEYS: &[&str] = &{:?};", keys).unwrap();
    // Placeholder names per key, as the template uses them.
    let mut placeholders: Vec<Vec<String>> = vec![];
    for key in &keys {
        let mut names: Vec<String> = declared[key].iter().map(|(n, _)| n.clone()).collect();
        for n in icu::placeholders(&icu::parse(&en[key])) {
            if !names.contains(&n) {
                names.push(n);
            }
        }
        placeholders.push(names);
    }
    let rows: Vec<String> = placeholders.iter().map(|p| format!("&{p:?}")).collect();
    writeln!(
        out,
        "pub const PLACEHOLDERS: &[&[&str]] = &[{}];",
        rows.join(", ")
    )
    .unwrap();
    let desktop_flags: Vec<bool> = keys.iter().map(|k| desktop_keys.contains(k)).collect();
    writeln!(
        out,
        "pub const IS_DESKTOP_KEY: &[bool] = &{:?};",
        desktop_flags
    )
    .unwrap();

    writeln!(
        out,
        "pub static MESSAGES: [&[Option<&str>; KEY_COUNT]; {}] = [",
        locales.len()
    )
    .unwrap();
    for locale in &locales {
        writeln!(out, "    &MSG_{},", locale.to_uppercase()).unwrap();
    }
    writeln!(out, "];").unwrap();
    for locale in &locales {
        let catalog = &catalogs[locale];
        writeln!(
            out,
            "static MSG_{}: [Option<&str>; KEY_COUNT] = [",
            locale.to_uppercase()
        )
        .unwrap();
        for key in &keys {
            match catalog.get(key) {
                Some(m) => writeln!(out, "    Some({m:?}),").unwrap(),
                None => writeln!(out, "    None,").unwrap(),
            }
        }
        writeln!(out, "];").unwrap();
    }

    // Accessor names, in key order.
    let mut used_names = BTreeSet::new();
    let mut accessors = vec![];
    for key in &keys {
        let mut name = snake(key);
        if RUST_KEYWORDS.contains(&name.as_str()) {
            name.push('_');
        }
        while !used_names.insert(name.clone()) {
            name.push('_');
        }
        accessors.push(name);
    }
    writeln!(out, "pub const ACCESSORS: &[&str] = &{:?};", accessors).unwrap();

    writeln!(out, "impl L10n {{").unwrap();
    for (index, key) in keys.iter().enumerate() {
        let name = &accessors[index];
        let plural_args = icu::plural_args(&icu::parse(&en[key]));
        let mut params = vec![];
        let mut args = vec![];
        for ph in &placeholders[index] {
            let ty = declared[key]
                .iter()
                .find(|(n, _)| n == ph)
                .map(|(_, t)| t.as_str())
                .unwrap_or(if plural_args.contains(ph) {
                    "int"
                } else {
                    "String"
                });
            let mut pname = snake(ph);
            if RUST_KEYWORDS.contains(&pname.as_str()) {
                pname.push('_');
            }
            let (rust_ty, arg) = match ty {
                "int" => ("i64", format!("Arg::Int({pname})")),
                "double" | "num" => ("f64", format!("Arg::Num({pname})")),
                _ => ("&str", format!("Arg::Str({pname})")),
            };
            params.push(format!("{pname}: {rust_ty}"));
            args.push(format!("({ph:?}, {arg})"));
        }
        let doc = en[key].replace('\n', " ");
        writeln!(out, "    /// `{key}`: {}", doc.replace('`', "'")).unwrap();
        if params.is_empty() {
            writeln!(
                out,
                "    pub fn {name}(&self) -> String {{ self.text({index}) }}"
            )
            .unwrap();
        } else {
            writeln!(
                out,
                "    pub fn {name}(&self, {}) -> String {{ self.format({index}, &[{}]) }}",
                params.join(", "),
                args.join(", ")
            )
            .unwrap();
        }
    }
    writeln!(out, "}}").unwrap();

    let dest = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("l10n_generated.rs");
    std::fs::write(dest, out).unwrap();
    model_logos(&manifest);
}

/// The App Intents (Shortcuts, Siri, Spotlight) on macOS: the Swift in
/// `intents/`, compiled by `packaging/macos/intents.sh compile` into a
/// static library linked whole into every binary of this crate (nothing in
/// Rust names the intents; the App Intents runtime finds them by their
/// Swift type names, from the bundle's `Metadata.appintents`). The library
/// calls back into `intents::conduit_intents_request`.
fn app_intents(manifest: &Path) {
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("macos") {
        return;
    }
    let dir = manifest.join("intents");
    let script = manifest.join("../../packaging/macos/intents.sh");
    println!("cargo:rerun-if-changed={}", dir.display());
    println!("cargo:rerun-if-changed={}", script.display());
    // intents.sh sources lib.sh, which reads release.env (MACOS_MIN).
    for sourced in ["lib.sh", "release.env"] {
        let path = manifest.join("../../packaging/macos").join(sourced);
        println!("cargo:rerun-if-changed={}", path.display());
    }
    println!("cargo:rerun-if-env-changed=MACOSX_DEPLOYMENT_TARGET");
    for entry in std::fs::read_dir(&dir).unwrap() {
        println!("cargo:rerun-if-changed={}", entry.unwrap().path().display());
    }
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("intents");
    let arch = match std::env::var("CARGO_CFG_TARGET_ARCH").as_deref() {
        Ok("aarch64") => "arm64",
        Ok(other) => other,
        Err(_) => "arm64",
    }
    .to_string();
    let status = std::process::Command::new("/bin/bash")
        .arg(&script)
        .arg("compile")
        .arg(&out)
        .env("CONDUIT_INTENTS_ARCH", &arch)
        .status()
        .unwrap_or_else(|e| panic!("{}: {e}", script.display()));
    assert!(
        status.success(),
        "the App Intents (intents/*.swift) did not compile"
    );
    println!("cargo:rustc-link-search=native={}", out.display());
    println!("cargo:rustc-link-lib=static:+whole-archive=conduit_intents");
    println!("cargo:rustc-link-lib=framework=AppIntents");
    println!("cargo:rustc-link-lib=framework=Foundation");
}

/// Apple's on-device Foundation Models on macOS: the Swift in `apple/`,
/// compiled by `packaging/macos/apple_models.sh compile` into a static
/// library that `shell::apple_models` calls (`conduit_apple_*`).
/// FoundationModels exists from macOS 26 and the app runs from 14, so the
/// framework is linked weakly: on an older macOS it is absent and the
/// engine says so.
fn apple_models(manifest: &Path) {
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("macos") {
        return;
    }
    let dir = manifest.join("apple");
    let script = manifest.join("../../packaging/macos/apple_models.sh");
    println!("cargo:rerun-if-changed={}", dir.display());
    println!("cargo:rerun-if-changed={}", script.display());
    println!("cargo:rerun-if-env-changed=MACOSX_DEPLOYMENT_TARGET");
    for entry in std::fs::read_dir(&dir).unwrap() {
        println!("cargo:rerun-if-changed={}", entry.unwrap().path().display());
    }
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("apple_models");
    let arch = match std::env::var("CARGO_CFG_TARGET_ARCH").as_deref() {
        Ok("aarch64") | Err(_) => "arm64".to_string(),
        Ok(other) => other.to_string(),
    };
    let status = std::process::Command::new("/bin/bash")
        .arg(&script)
        .arg("compile")
        .arg(&out)
        .env("CONDUIT_APPLE_ARCH", &arch)
        .status()
        .unwrap_or_else(|e| panic!("{}: {e}", script.display()));
    assert!(
        status.success(),
        "the Apple models engine (apple/*.swift) did not compile"
    );
    // What an SDK older than macOS 27's (Xcode 26) leaves out of the engine
    // (`apple_models.sh sdk-gaps`): said on every build, never silent.
    if let Ok(gaps) = std::fs::read_to_string(out.join("sdk-gaps.txt")) {
        for gap in gaps.lines().filter(|l| !l.trim().is_empty()) {
            println!("cargo:warning=Apple models: {gap}");
        }
    }
    println!("cargo:rustc-link-search=native={}", out.display());
    println!("cargo:rustc-link-lib=static=conduit_apple_models");
    println!("cargo:rustc-link-arg=-Wl,-weak_framework,FoundationModels");
    println!("cargo:rustc-link-lib=framework=Foundation");
}

/// Where the Swift libraries ([`app_intents`], [`apple_models`]) find
/// their runtime, said once for both.
fn swift_runtime() {
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("macos") {
        return;
    }
    // The Swift runtime is the system's (/usr/lib/swift); the toolchain's
    // folder has the back-deployment shims the object may ask for. Below
    // macOS 12 as the deployment target (cargo's default, 11.0, for dev
    // builds; bundle.sh sets 14.0), the linker names Swift Concurrency by
    // `@rpath`, so the system's folder is on the rpath too.
    println!("cargo:rustc-link-search=native=/usr/lib/swift");
    println!("cargo:rustc-link-arg=-Wl,-rpath,/usr/lib/swift");
    let swiftc = std::process::Command::new("xcrun")
        .args(["--sdk", "macosx", "--find", "swiftc"])
        .output()
        .ok()
        .filter(|o| o.status.success())
        .map(|o| PathBuf::from(String::from_utf8_lossy(&o.stdout).trim()));
    if let Some(toolchain) = swiftc.as_deref().and_then(|s| s.parent()?.parent()) {
        let lib = toolchain.join("lib/swift/macosx");
        println!("cargo:rustc-link-search=native={}", lib.display());
    }
}

const RUST_KEYWORDS: &[&str] = &[
    "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for",
    "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return",
    "self", "static", "struct", "super", "trait", "true", "type", "unsafe", "use", "where",
    "while", "async", "await", "dyn", "abstract", "become", "box", "do", "final", "macro",
    "override", "priv", "typeof", "unsized", "virtual", "yield", "try", "gen", "text", "format",
    "locale", "new",
];

/// `<dir>/<prefix><locale>.arb`, sorted by locale.
fn arb_files(dir: &Path, prefix: &str) -> Vec<(String, PathBuf)> {
    let mut files = vec![];
    for entry in std::fs::read_dir(dir).unwrap_or_else(|e| panic!("{}: {e}", dir.display())) {
        let path = entry.unwrap().path();
        let Some(name) = path.file_name().and_then(|n| n.to_str()) else {
            continue;
        };
        if let Some(locale) = name
            .strip_prefix(prefix)
            .and_then(|n| n.strip_suffix(".arb"))
        {
            files.push((locale.to_string(), path.clone()));
        }
    }
    files.sort();
    files
}

/// `fooBarURL` → `foo_bar_url`.
fn snake(s: &str) -> String {
    let chars: Vec<char> = s.chars().collect();
    let mut out = String::new();
    for (i, &c) in chars.iter().enumerate() {
        if c.is_ascii_uppercase() {
            let prev_lower =
                i > 0 && (chars[i - 1].is_ascii_lowercase() || chars[i - 1].is_ascii_digit());
            let next_lower = chars.get(i + 1).is_some_and(|n| n.is_ascii_lowercase());
            let prev_upper = i > 0 && chars[i - 1].is_ascii_uppercase();
            if i > 0 && (prev_lower || (prev_upper && next_lower)) {
                out.push('_');
            }
            out.push(c.to_ascii_lowercase());
        } else if c.is_ascii_alphanumeric() {
            out.push(c);
        } else {
            out.push('_');
        }
    }
    if out.starts_with(|c: char| c.is_ascii_digit()) {
        out.insert(0, '_');
    }
    out
}

/// `$OUT_DIR/model_logos.rs`: the models.dev logos the app bundles
/// (`assets/model_logos/*.svg`, the same set mobile ships), as a sorted
/// table of `(logo id, SVG bytes)`, and the catalog the daemon picks them
/// from (`MODEL_LOGO_CATALOG_DIR`, for a run from the checkout).
fn model_logos(manifest: &Path) {
    let dir = manifest.join("../../../assets/model_logos");
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut logos: Vec<(String, PathBuf)> = std::fs::read_dir(&dir)
        .map(|entries| {
            entries
                .filter_map(Result::ok)
                .map(|e| e.path())
                .filter(|p| p.extension().is_some_and(|x| x == "svg"))
                .filter_map(|p| {
                    let id = p.file_stem()?.to_str()?.to_string();
                    Some((id, p))
                })
                .collect()
        })
        .unwrap_or_default();
    logos.sort();
    let mut out = String::from("pub static MODEL_LOGOS: &[(&str, &[u8])] = &[\n");
    for (id, path) in &logos {
        let path = path.canonicalize().unwrap_or_else(|_| path.clone());
        writeln!(
            out,
            "    ({id:?}, include_bytes!({:?})),",
            path.display().to_string()
        )
        .unwrap();
    }
    out.push_str("];\n");
    let catalog = dir.canonicalize().unwrap_or(dir);
    writeln!(
        out,
        "pub const MODEL_LOGO_CATALOG_DIR: &str = {:?};",
        catalog.display().to_string()
    )
    .unwrap();
    let dest = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("model_logos.rs");
    std::fs::write(dest, out).unwrap();
}
