/// [name] as a Swift identifier: a keyword in backticks.
String _id(String name, String where) {
  if (_unusable.contains(name)) {
    throw GeneratorError('$where.$name: not a usable Swift name');
  }
  return _swiftKeywords.contains(name) ? '`$name`' : name;
}

/// [name] as an argument label, where only `inout`, `var` and `let` need
/// backticks.
String _label(String name) =>
    const {'inout', 'var', 'let'}.contains(name) ? '`$name`' : name;

/// [name] as a nested type's name.
String _typeId(String name, String where) {
  if (_unusable.contains(name) || name == 'Protocol') {
    throw GeneratorError('$where.$name: not a usable Swift type name');
  }
  return _swiftKeywords.contains(name) ? '`$name`' : name;
}

String _optional(String? name) => name == null ? 'nil' : _str(name);

/// A Swift string literal.
String _str(String value) {
  final buffer = StringBuffer('"');
  for (final rune in value.runes) {
    buffer.write(switch (rune) {
      0x5C => r'\\',
      0x22 => r'\"',
      0x0A => r'\n',
      0x0D => r'\r',
      0x09 => r'\t',
      0x00 => r'\0',
      < 0x20 || 0x7F => '\\u{${rune.toRadixString(16)}}',
      _ => String.fromCharCode(rune),
    });
  }
  return (buffer..write('"')).toString();
}
