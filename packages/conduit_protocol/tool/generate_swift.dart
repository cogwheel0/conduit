// Writes ios/ConduitProtocol/Sources/ConduitProtocol/Generated.swift: the
// protocol's DTOs, enums, error codes and method and event tables, as Swift.
//
//   dart run tool/generate_swift.dart           # write it
//   dart run tool/generate_swift.dart --check   # exit 1 when it is stale
//
// It reads the Dart source as generate_rust.dart does
// (tool/src/protocol_source.dart) and writes code that needs no formatter,
// so it runs with Dart alone.
import 'dart:io';

import 'package:analyzer/dart/ast/ast.dart';
import 'package:analyzer/dart/ast/token.dart';

import 'src/protocol_source.dart';

/// Written by hand in the package (`RpcError.swift`), which the generated
/// code refers to by the same name.
const Set<String> _handWritten = <String>{'RpcError'};

void main(List<String> args) {
  final check = args.contains('--check');
  final package = Directory.fromUri(Platform.script.resolve('..'));
  final repo = package.parent.parent;
  final output = File(
    '${repo.path}/ios/ConduitProtocol/Sources/ConduitProtocol/'
    'Generated.swift',
  );

  final source = ProtocolSource.read(
    Directory('${package.path}/lib/src'),
    handWritten: _handWritten,
  );
  final swift = SwiftEmitter(source).emit();

  if (check) {
    if (!output.existsSync() || output.readAsStringSync() != swift) {
      stderr.writeln(
        '${output.path} is stale: run `dart run tool/generate_swift.dart` '
        'in packages/conduit_protocol.',
      );
      exitCode = 1;
    }
    return;
  }
  output.writeAsStringSync(swift);
  stdout.writeln(
    'Wrote ${source.dtos.length - _handWritten.length} structs, '
    '${source.enums.length} enums, ${source.methods.length} methods and '
    '${source.events.length} events to ${output.path}',
  );
}

// ---------------------------------------------------------------------------
// Writing Swift
// ---------------------------------------------------------------------------

/// Words Swift reserves, which an identifier takes in backticks.
const Set<String> _swiftKeywords = <String>{
  'associatedtype', 'class', 'deinit', 'enum', 'extension', 'fileprivate', //
  'func', 'import', 'init', 'inout', 'internal', 'let', 'open', 'operator',
  'private', 'precedencegroup', 'protocol', 'public', 'rethrows', 'static',
  'struct', 'subscript', 'typealias', 'var', 'break', 'case', 'catch',
  'continue', 'default', 'defer', 'do', 'else', 'fallthrough', 'for',
  'guard', 'if', 'in', 'repeat', 'return', 'throw', 'switch', 'where',
  'while', 'Any', 'as', 'await', 'false', 'is', 'nil', 'super', 'throws',
  'true', 'try',
};

/// Names no identifier may take, even in backticks.
const Set<String> _unusable = <String>{'self', 'Self', '_', 'Type'};

/// Every type, protocol and module name the package's sources and tests
/// write unqualified, Swift's and Foundation's and its own: a DTO or enum of
/// one of these names would shadow it inside the module, so none may take
/// one.
const Set<String> _reservedTypeNames = <String>{
  // Swift and Foundation.
  'Any', 'Array', 'AsyncStream', 'Bool', 'CancellationError', //
  'CheckedContinuation', 'Codable', 'CodingKey', 'CodingKeys',
  'CustomStringConvertible', 'Data', 'Decodable', 'Decoder', 'Dictionary',
  'Double', 'Encodable', 'Encoder', 'Equatable', 'Error', 'Foundation',
  'Hashable', 'Int', 'Int64', 'JSONDecoder', 'JSONEncoder', 'NSLock', 'Never',
  'Optional', 'RawRepresentable', 'Result', 'Sendable', 'Set', 'String',
  'Swift', 'Task', 'URL', 'Void', 'XCTest', 'XCTestCase',
  // The package's own.
  'ConduitProtocol', 'JSONValue', 'RpcClient', 'RpcTransport',
  'ConduitMethod', 'ConduitEvent', 'EmptyParams', 'EmptyResult',
  'ErrorObject', 'MethodSpec', 'EventSpec', 'Methods', 'EventNames',
  'Conformance', 'ErrorCode', 'NoCodingKeys', 'OutgoingRequest', 'Routes',
};

final class SwiftEmitter {
  SwiftEmitter(this.source);

  final ProtocolSource source;
  final StringBuffer _out = StringBuffer();

  String emit() {
    for (final dto in source.dtos) {
      if (_reservedTypeNames.contains(dto.name)) {
        throw GeneratorError('${dto.name}: a name the Swift code relies on');
      }
    }
    for (final def in source.enums) {
      if (_reservedTypeNames.contains(def.name)) {
        throw GeneratorError('${def.name}: a name the Swift code relies on');
      }
    }
    _emitVersion();
    for (final item in source.declarations) {
      switch (item) {
        case EnumDef():
          _emitEnum(item);
        case Dto() when !_handWritten.contains(item.name):
          _emitStruct(item);
      }
    }
    _emitErrorCodes();
    _emitMethods();
    _emitEvents();
    _emitConformance();

    final header = StringBuffer()
      ..writeln(
        '// @generated by packages/conduit_protocol/tool/generate_swift.dart '
        'from',
      )
      ..writeln(
        '// packages/conduit_protocol/lib/src. Do not edit by hand: change the '
        'Dart',
      )
      ..writeln('// source and run `dart run tool/generate_swift.dart` there.')
      ..writeln('//')
      ..writeln(
        '// A field with a Dart default reads a JSON null as that default, as '
        'Dart does;',
      )
      ..writeln('// the Rust types are stricter and refuse it.')
      ..writeln()
      ..writeln('import Foundation')
      ..writeln();
    return '$header${_out.toString().trimRight()}\n';
  }

  void _docs(List<String> lines, [String indent = '']) {
    var start = 0;
    var end = lines.length;
    while (start < end && lines[start].isEmpty) {
      start++;
    }
    while (end > start && lines[end - 1].isEmpty) {
      end--;
    }
    for (final line in lines.sublist(start, end)) {
      _out.writeln(line.isEmpty ? '$indent///' : '$indent/// $line');
    }
  }

  void _emitVersion() {
    final version = source.topString('kConduitProtocolVersion');
    _docs(source.topDocs['kConduitProtocolVersion']!);
    _out
      ..writeln('public let protocolVersion = ${_str(version)}')
      ..writeln();
  }

  // Enums ------------------------------------------------------------------

  /// The Dart value called `unknown`, which doubles as the fallback.
  EnumValue? _ownUnknown(EnumDef def) =>
      def.values.where((v) => v.name == 'unknown').firstOrNull;

  /// [value] as a Swift expression of its enum.
  String _enumCase(EnumDef def, EnumValue value) =>
      identical(value, _ownUnknown(def))
      ? '.unknown(${_str(value.wire)})'
      : '.${_id(value.name, def.name)}';

  void _emitEnum(EnumDef def) {
    final own = _ownUnknown(def);
    final known = [
      for (final value in def.values)
        if (!identical(value, own)) value,
    ];
    for (final value in known) {
      if (value.name == 'rawValue') {
        throw GeneratorError('${def.name}: a value called rawValue');
      }
    }
    _docs(def.docs);
    _out.writeln('public enum ${def.name}: Codable, Hashable, Sendable {');
    for (final value in known) {
      _docs(value.docs, '  ');
      _out.writeln('  case ${_id(value.name, def.name)}');
    }
    if (own != null) {
      _docs(own.docs, '  ');
      if (own.docs.isNotEmpty) _out.writeln('  ///');
      _out.writeln(
        '  /// Also what a value this build does not know decodes as, kept '
        'as it came.',
      );
    } else {
      _out.writeln(
        '  /// A value this build does not know, from a newer core, kept as '
        'it came.',
      );
    }
    _out
      ..writeln('  case unknown(String)')
      ..writeln()
      ..writeln('  public init(rawValue: String) {')
      ..writeln('    switch rawValue {');
    for (final value in known) {
      _out.writeln(
        '    case ${_str(value.wire)}: self = .${_id(value.name, def.name)}',
      );
    }
    _out
      ..writeln('    default: self = .unknown(rawValue)')
      ..writeln('    }')
      ..writeln('  }')
      ..writeln()
      ..writeln('  /// The value as it goes on the wire.')
      ..writeln('  public var rawValue: String {')
      ..writeln('    switch self {');
    for (final value in known) {
      _out.writeln(
        '    case .${_id(value.name, def.name)}: return ${_str(value.wire)}',
      );
    }
    _out
      ..writeln('    case .unknown(let raw): return raw')
      ..writeln('    }')
      ..writeln('  }')
      ..writeln()
      ..writeln('  public init(from decoder: Decoder) throws {')
      ..writeln(
        '    self.init(rawValue: try decoder.singleValueContainer()'
        '.decode(String.self))',
      )
      ..writeln('  }')
      ..writeln()
      ..writeln('  public func encode(to encoder: Encoder) throws {')
      ..writeln('    var container = encoder.singleValueContainer()')
      ..writeln('    try container.encode(rawValue)')
      ..writeln('  }')
      ..writeln('}')
      ..writeln();
  }

  // Structs ----------------------------------------------------------------

  void _emitStruct(Dto dto) {
    String where(DtoField field) => '${dto.name}.${field.name}';
    final defaults = <DtoField, String>{};
    for (final field in dto.fields) {
      if (field.isOptional) {
        if (field.defaultValue != null && field.defaultValue is! NullLiteral) {
          throw GeneratorError(
            '${where(field)}: a non-null default on a nullable field is not '
            'supported',
          );
        }
      } else if (field.defaultValue != null) {
        defaults[field] = _value(field.defaultValue!, field.type, where(field));
      }
    }

    _docs(dto.docs);
    _out.writeln('public struct ${dto.name}: Codable, Equatable, Sendable {');
    for (final field in dto.fields) {
      _docs(field.docs, '  ');
      _out.writeln(
        '  public var ${_id(field.name, dto.name)}: ${_fieldType(field)}',
      );
    }
    if (dto.fields.isNotEmpty) _out.writeln();

    // The memberwise init: what has a default may be left out.
    if (dto.fields.isEmpty) {
      _out.writeln('  public init() {}');
    } else {
      _out.writeln('  public init(');
      for (final (i, field) in dto.fields.indexed) {
        final id = _id(field.name, dto.name);
        final fallback = field.isOptional ? ' = nil' : _default(defaults[field]);
        final comma = i == dto.fields.length - 1 ? '' : ',';
        _out.writeln('    $id: ${_fieldType(field)}$fallback$comma');
      }
      _out.writeln('  ) {');
      for (final field in dto.fields) {
        final id = _id(field.name, dto.name);
        _out.writeln('    self.$id = $id');
      }
      _out.writeln('  }');
    }
    _out.writeln();

    if (dto.fields.isEmpty) {
      _out
        ..writeln('  public init(from decoder: Decoder) throws {')
        ..writeln('    _ = try decoder.container(keyedBy: NoCodingKeys.self)')
        ..writeln('  }')
        ..writeln()
        ..writeln('  public func encode(to encoder: Encoder) throws {')
        ..writeln('    _ = encoder.container(keyedBy: NoCodingKeys.self)')
        ..writeln('  }')
        ..writeln('}')
        ..writeln();
      return;
    }

    _out.writeln('  private enum CodingKeys: String, CodingKey {');
    for (final field in dto.fields) {
      final id = _id(field.name, dto.name);
      _out.writeln(
        field.jsonName == field.name
            ? '    case $id'
            : '    case $id = ${_str(field.jsonName)}',
      );
    }
    _out
      ..writeln('  }')
      ..writeln()
      ..writeln('  public init(from decoder: Decoder) throws {')
      ..writeln(
        '    let container = try decoder.container(keyedBy: CodingKeys.self)',
      );
    for (final field in dto.fields) {
      final id = _id(field.name, dto.name);
      final type = field.isOptional
          ? _type(field.type.nonNull, where(field))
          : _fieldType(field);
      final fallback = defaults[field];
      final read = field.isOptional
          ? 'try container.decodeIfPresent($type.self, forKey: .$id)'
          : fallback != null
          ? 'try container.decodeIfPresent($type.self, forKey: .$id) '
                '?? $fallback'
          : 'try container.decode($type.self, forKey: .$id)';
      _out.writeln('    self.$id = $read');
    }
    _out
      ..writeln('  }')
      ..writeln()
      ..writeln('  public func encode(to encoder: Encoder) throws {')
      ..writeln('    var container = encoder.container(keyedBy: CodingKeys.self)');
    for (final field in dto.fields) {
      final id = _id(field.name, dto.name);
      if (!field.isOptional) {
        _out.writeln('    try container.encode(self.$id, forKey: .$id)');
      } else if (field.includeIfNull) {
        _out
          ..writeln('    if let value = self.$id {')
          ..writeln('      try container.encode(value, forKey: .$id)')
          ..writeln('    } else {')
          ..writeln('      try container.encodeNil(forKey: .$id)')
          ..writeln('    }');
      } else {
        _out.writeln(
          '    try container.encodeIfPresent(self.$id, forKey: .$id)',
        );
      }
    }
    _out
      ..writeln('  }')
      ..writeln('}')
      ..writeln();
  }

  static String _default(String? value) => value == null ? '' : ' = $value';

  String _fieldType(DtoField field) {
    final where = field.name;
    if (field.isOptional) return '${_type(field.type.nonNull, where)}?';
    return _type(field.type, where);
  }

  /// The Swift type for a non-null Dart type.
  String _type(TypeRef type, String where) {
    switch (type.name) {
      case 'String':
        return 'String';
      case 'bool':
        return 'Bool';
      case 'int':
        return 'Int';
      case 'double' || 'num':
        return 'Double';
      case 'dynamic' || 'Object':
        return 'JSONValue';
      case 'List':
        return '[${_elementType(type.args.single, where)}]';
      case 'Map':
        final key = type.args[0];
        if (key.name != 'String' || key.nullable) {
          throw GeneratorError('$where: map keys must be String');
        }
        // An untyped map is still an object: its values are any JSON.
        if (type.args[1].isAny) return '[String: JSONValue]';
        return '[String: ${_elementType(type.args[1], where)}]';
    }
    if (source.isType(type.name)) return type.name;
    throw GeneratorError('$where: no Swift type for `$type`');
  }

  String _elementType(TypeRef type, String where) =>
      type.nullable && !type.isAny
      ? '${_type(type.nonNull, where)}?'
      : _type(type, where);

  // Default values -----------------------------------------------------------

  /// [node] as a Swift expression of [type]'s Swift type.
  String _value(Expression node, TypeRef type, String where) {
    final value = source.resolve(node);
    if (value is NullLiteral) {
      if (!type.nullable) throw GeneratorError('$where: null for $type');
      return 'nil';
    }
    if (type.nullable && !type.isAny) {
      return _value(value, type.nonNull, where);
    }
    Never fail() =>
        throw GeneratorError('$where: unsupported default `$node` for $type');
    switch (type.name) {
      case 'bool':
        return value is BooleanLiteral ? '${value.value}' : fail();
      case 'int':
        return switch (value) {
          IntegerLiteral(value: final int number) => '$number',
          PrefixExpression(
            operator: Token(lexeme: '-'),
            operand: IntegerLiteral(value: final int number),
          ) =>
            '-$number',
          _ => fail(),
        };
      case 'double' || 'num':
        final number = switch (value) {
          IntegerLiteral(value: final int number) => number.toDouble(),
          DoubleLiteral(value: final number) => number,
          _ => fail(),
        };
        final text = '$number';
        return text.contains('.') || text.contains('e') ? text : '$text.0';
      case 'String':
        if (value is! SimpleStringLiteral) fail();
        return _str(value.value);
      case 'List':
        if (value is! ListLiteral) fail();
        final elements = <String>[
          for (final element in value.elements)
            _value(element as Expression, type.args.single, where),
        ];
        return '[${elements.join(', ')}]';
      case 'Map':
        if (value is! SetOrMapLiteral || value.elements.isNotEmpty) fail();
        return '[:]';
    }
    final enumDef = source.enumDef(type.name);
    if (enumDef != null) {
      if (value is PrefixedIdentifier && value.prefix.name == enumDef.name) {
        final named = enumDef.values
            .where((v) => v.name == value.identifier.name)
            .firstOrNull;
        if (named != null) return _enumCase(enumDef, named);
      }
      fail();
    }
    final dto = source.dto(type.name);
    if (dto == null || constructedType(value) != dto.name) fail();
    final args = constructorArguments(value) ?? fail();
    final given = <String, Expression>{};
    for (final arg in args) {
      if (arg is! NamedArgument) fail();
      given[arg.name.lexeme] = arg.argumentExpression;
    }
    // Swift takes the arguments in the order the fields are declared.
    final fields = <String>[
      for (final field in dto.fields)
        if (given[field.name] case final expression?)
          '${_label(field.name)}: '
              '${_value(expression, field.type, '$where.${field.name}')}',
    ];
    return '${dto.name}(${fields.join(', ')})';
  }

  // Error codes --------------------------------------------------------------

  void _emitErrorCodes() {
    final codes = source.namedConsts['ConduitErrorCodes']!;
    for (final code in codes) {
      if (code.field == 'other' || code.field == 'rawValue') {
        throw GeneratorError('ConduitErrorCodes.${code.field}: a name taken');
      }
    }
    _out
      ..writeln(
        '/// A stable error identifier: what `RpcError.code` carries. The app',
      )
      ..writeln('/// localizes each one; the core never sends prose.')
      ..writeln(
        'public enum ErrorCode: Codable, Hashable, Sendable, '
        'CustomStringConvertible {',
      );
    for (final code in codes) {
      _docs(<String>[
        ...code.docs,
        if (code.docs.isNotEmpty) '',
        '`${code.value}`',
      ], '  ');
      _out.writeln('  case ${_id(code.field, 'ConduitErrorCodes')}');
    }
    _out
      ..writeln('  /// A code this build does not know, kept as it came.')
      ..writeln('  case other(String)')
      ..writeln()
      ..writeln(
        '  /// Reads a wire code; one this build does not know is `.other`.',
      )
      ..writeln('  public init(rawValue: String) {')
      ..writeln('    switch rawValue {');
    for (final code in codes) {
      _out.writeln(
        '    case ${_str(code.value)}: '
        'self = .${_id(code.field, 'ConduitErrorCodes')}',
      );
    }
    _out
      ..writeln('    default: self = .other(rawValue)')
      ..writeln('    }')
      ..writeln('  }')
      ..writeln()
      ..writeln('  /// The code as it goes on the wire.')
      ..writeln('  public var rawValue: String {')
      ..writeln('    switch self {');
    for (final code in codes) {
      _out.writeln(
        '    case .${_id(code.field, 'ConduitErrorCodes')}: '
        'return ${_str(code.value)}',
      );
    }
    _out
      ..writeln('    case .other(let code): return code')
      ..writeln('    }')
      ..writeln('  }')
      ..writeln()
      ..writeln('  public var description: String { rawValue }')
      ..writeln()
      ..writeln('  public init(from decoder: Decoder) throws {')
      ..writeln(
        '    self.init(rawValue: try decoder.singleValueContainer()'
        '.decode(String.self))',
      )
      ..writeln('  }')
      ..writeln()
      ..writeln('  public func encode(to encoder: Encoder) throws {')
      ..writeln('    var container = encoder.singleValueContainer()')
      ..writeln('    try container.encode(rawValue)')
      ..writeln('  }')
      ..writeln('}')
      ..writeln();
  }

  // Methods ------------------------------------------------------------------

  /// A DTO named from inside `Methods`, where a method's own type could
  /// shadow it.
  String _qualified(String? name, String none) =>
      name == null ? none : 'ConduitProtocol.$name';

  void _emitMethods() {
    _out
      ..writeln(
        '/// The RPC methods, one caseless enum each, so a call is typed by its',
      )
      ..writeln(
        '/// method: `M.name` goes on the wire with an `M.Params`, and the '
        'reply',
      )
      ..writeln('/// decodes as an `M.Result`.')
      ..writeln('public enum Methods {');
    for (final method in source.methods) {
      final type = _typeId(pascalCase(method.field), 'ConduitMethodSpecs');
      _docs(<String>[
        ...method.docs,
        if (method.docs.isNotEmpty) '',
        '`${method.name}`: ${method.params ?? 'no params'} -> '
            '${method.result ?? 'no result'}.',
      ], '  ');
      _out
        ..writeln('  public enum $type: ConduitMethod {')
        ..writeln('    public static let name = ${_str(method.name)}')
        ..writeln(
          '    public typealias Params = '
          '${_qualified(method.params, 'EmptyParams')}',
        )
        ..writeln(
          '    public typealias Result = '
          '${_qualified(method.result, 'EmptyResult')}',
        )
        ..writeln('  }')
        ..writeln();
    }
    _out
      ..writeln('}')
      ..writeln()
      ..writeln(
        '/// Every method, with its params and result DTOs by name (nil for '
        'none).',
      )
      ..writeln('public let methodSpecs: [MethodSpec] = [');
    for (final method in source.methods) {
      _out.writeln(
        '  MethodSpec(name: ${_str(method.name)}, '
        'params: ${_optional(method.params)}, '
        'result: ${_optional(method.result)}),',
      );
    }
    _out
      ..writeln(']')
      ..writeln();
  }

  // Events -------------------------------------------------------------------

  void _emitEvents() {
    final events = source.events;
    String id(EventSpecDef e) => _id(e.field, 'ConduitEventSpecs');

    _out
      ..writeln('/// The event names, for `events.subscribe`.')
      ..writeln('public enum EventNames {');
    for (final event in events) {
      _docs(event.docs, '  ');
      _out.writeln('  public static let ${id(event)} = ${_str(event.name)}');
    }
    _out
      ..writeln('}')
      ..writeln()
      ..writeln(
        '/// Every event, with its payload DTO by name and whether it is '
        'scoped.',
      )
      ..writeln('public let eventSpecs: [EventSpec] = [');
    for (final event in events) {
      _out.writeln(
        '  EventSpec(name: ${_str(event.name)}, '
        'payload: ${_optional(event.payload)}, scoped: ${event.scoped}),',
      );
    }
    _out
      ..writeln(']')
      ..writeln()
      ..writeln('/// An event the core pushed, decoded from its envelope by name.')
      ..writeln('///')
      ..writeln(
        '/// An event without a payload is a case without one: the screen '
        'refetches what',
      )
      ..writeln('/// it names. One this build does not know is `.unknown`.')
      ..writeln('public enum ConduitEvent: Equatable, Sendable {');
    for (final event in events) {
      _docs(<String>[
        ...event.docs,
        if (event.docs.isNotEmpty) '',
        '`${event.name}`${event.scoped ? ', scoped' : ''}.',
      ], '  ');
      final payload = event.payload;
      _out.writeln(
        payload == null ? '  case ${id(event)}' : '  case ${id(event)}($payload)',
      );
    }
    _out
      ..writeln(
        '  /// An event this build does not know, from a newer core, kept as '
        'it came.',
      )
      ..writeln('  case unknown(name: String, payload: JSONValue)')
      ..writeln()
      ..writeln('  /// Decodes `payload` as the event called `name`.')
      ..writeln('  ///')
      ..writeln(
        '  /// A name this build does not know is `.unknown`; a known one '
        'whose payload',
      )
      ..writeln(
        '  /// does not fit its DTO throws. An event without a payload '
        'ignores whatever',
      )
      ..writeln('  /// it carries.')
      ..writeln(
        '  public static func decode(name: String, payload: JSONValue) throws '
        '-> ConduitEvent {',
      )
      ..writeln('    switch name {');
    for (final event in events) {
      final payload = event.payload;
      _out.writeln(
        payload == null
            ? '    case EventNames.${id(event)}: return .${id(event)}'
            : '    case EventNames.${id(event)}: '
                  'return .${id(event)}(try payload.decode($payload.self))',
      );
    }
    _out
      ..writeln('    default: return .unknown(name: name, payload: payload)')
      ..writeln('    }')
      ..writeln('  }')
      ..writeln()
      ..writeln("  /// The event's name, as the envelope carries it.")
      ..writeln('  public var name: String {')
      ..writeln('    switch self {');
    for (final event in events) {
      _out.writeln('    case .${id(event)}: return EventNames.${id(event)}');
    }
    _out
      ..writeln('    case .unknown(let name, _): return name')
      ..writeln('    }')
      ..writeln('  }')
      ..writeln()
      ..writeln(
        "  /// Whether this build's event table publishes the event with a "
        'scope; false',
      )
      ..writeln(
        "  /// for an unknown one. To route an event, read its envelope's "
        '`scope`.',
      )
      ..writeln('  public var isScoped: Bool {')
      ..writeln('    switch self {');
    final scoped = [
      for (final event in events)
        if (event.scoped) event,
    ];
    if (scoped.isNotEmpty) {
      _out.writeln(
        '    case ${scoped.map((e) => '.${id(e)}').join(', ')}: return true',
      );
    }
    _out
      ..writeln('    default: return false')
      ..writeln('    }')
      ..writeln('  }')
      ..writeln()
      ..writeln(
        '  /// The payload as JSON, as the envelope carries it: an empty '
        'object for an',
      )
      ..writeln('  /// event without one.')
      ..writeln('  public func payload() throws -> JSONValue {')
      ..writeln('    switch self {');
    for (final event in events) {
      _out.writeln(
        event.payload == null
            ? '    case .${id(event)}: return .object([:])'
            : '    case .${id(event)}(let payload): '
                  'return try JSONValue(encoding: payload)',
      );
    }
    _out
      ..writeln('    case .unknown(_, let payload): return payload')
      ..writeln('    }')
      ..writeln('  }')
      ..writeln('}')
      ..writeln();
  }

  // Conformance ---------------------------------------------------------------

  void _emitConformance() {
    final names = <String>[for (final dto in source.dtos) dto.name]..sort();
    _out
      ..writeln('/// For the conformance tests: every DTO by its Dart name.')
      ..writeln('public enum Conformance {')
      ..writeln("  /// Every DTO's name.")
      ..writeln('  public static let typeNames: [String] = [');
    for (final name in names) {
      _out.writeln('    ${_str(name)},');
    }
    _out
      ..writeln('  ]')
      ..writeln()
      ..writeln(
        '  /// Decodes `json` as the DTO called `typeName` and encodes it '
        'again; nil for',
      )
      ..writeln('  /// a name that is not a DTO.')
      ..writeln(
        '  public static func roundTrip(_ typeName: String, _ json: JSONValue) '
        'throws -> JSONValue? {',
      )
      ..writeln('    switch typeName {');
    for (final name in names) {
      _out.writeln(
        '    case ${_str(name)}: return try json.roundTrip($name.self)',
      );
    }
    _out
      ..writeln('    default: return nil')
      ..writeln('    }')
      ..writeln('  }')
      ..writeln('}');
  }
}

