// Regenerates the goldens from the live DTOs:
//
// * test/src/protocol_goldens.dart, which the Dart tests compare against;
// * goldens/<fixture>.json, one file per fixture, plus goldens/manifest.json
//   (fixture name -> DTO type name) and goldens/specs.json (the method and
//   event tables), which other languages' tests read: the Rust crate in
//   desktop/crates/protocol decodes and re-encodes every one.
//
//   dart run tool/dump_goldens.dart
//
// Review the diff before committing. An unexplained change here means the wire
// format moved, which requires bumping `kConduitProtocolVersion`.
import 'dart:io';

import '../test/src/golden_files.dart';
import '../test/src/protocol_fixtures.dart';

void main() {
  final buffer = StringBuffer()
    ..writeln('// GENERATED by tool/dump_goldens.dart — do not edit by hand.')
    ..writeln('//')
    ..writeln('// The exact bytes each DTO puts on the wire. Checked in so a')
    ..writeln('// change to any `@freezed` class shows up as a reviewable diff')
    ..writeln('// rather than as a silent protocol break.')
    ..writeln()
    ..writeln('const Map<String, String> protocolGoldens = <String, String>{');
  for (final entry in protocolFixtures.entries) {
    final json = goldenEncoder.convert(encodeFixture(entry.value));
    if (json.contains("'''") || json.contains(r'\')) {
      throw StateError(
        'Fixture "${entry.key}" contains a sequence that cannot be embedded '
        'in a raw triple-quoted string. Adjust the fixture or the emitter.',
      );
    }
    buffer
      ..writeln("  '${entry.key}': r'''")
      ..writeln("$json''',")
      ..writeln();
  }
  buffer.writeln('};');
  File('test/src/protocol_goldens.dart').writeAsStringSync(buffer.toString());

  final files = expectedGoldenFiles();
  final dir = Directory(goldensDir)..createSync();
  for (final MapEntry(key: name, value: contents) in files.entries) {
    File('$goldensDir/$name').writeAsStringSync(contents);
  }
  stdout.writeln(
    'Wrote ${protocolFixtures.length} goldens to '
    'test/src/protocol_goldens.dart and ${files.length} files to '
    '$goldensDir/',
  );

  // Not deleted here: a stale file is a renamed or removed fixture, and
  // whoever made that change should see it go in the diff.
  final stale = <String>[
    for (final entity in dir.listSync())
      if (entity is File && !files.containsKey(_basename(entity.path)))
        entity.path,
  ]..sort();
  if (stale.isNotEmpty) {
    stderr.writeln(
      'Stale files in $goldensDir/ (no fixture writes them; remove them):\n'
      '  ${stale.join('\n  ')}',
    );
    exitCode = 1;
  }
}

String _basename(String path) => path.split(Platform.pathSeparator).last;
