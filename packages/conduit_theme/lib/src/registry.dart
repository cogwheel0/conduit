/// The palette used when a stored id is unknown or missing.
///
/// Falling back rather than throwing matters on upgrade: a settings file
/// written by a build that had an extra palette must still open.
final ThemePalette kDefaultPalette = kConduitPalettes.first;

/// Looks up a palette by its stored [id], falling back to [kDefaultPalette].
ThemePalette paletteById(String? id) {
  for (final palette in kConduitPalettes) {
    if (palette.id == id) return palette;
  }
  return kDefaultPalette;
}
