final RegExp _wordStart = RegExp(r'(^|[\s_\-./+])([a-z])');

/// The name to show for a fenced code block's language id, such as "Python"
/// for `py` or "C++" for `cpp`, or null when the block has no particular
/// language (the caller shows its own localized "Plain Text").
///
/// Unknown ids keep their spelling with each word capitalised
/// (`my-lang` → "My-Lang", `shell_session` → "Shell Session"); ids that
/// already contain capitals are shown as written.
String? codeLanguageDisplayName(String id) {
  final trimmed = id.trim();
  final key = trimmed.toLowerCase();
  if (_plainTextIds.contains(key)) return null;
  final known = _languageNames[key];
  if (known != null) return known;
  if (trimmed != key) return trimmed;
  return key
      .replaceAll('_', ' ')
      .replaceAllMapped(
        _wordStart,
        (match) => '${match[1]}${match[2]!.toUpperCase()}',
      );
}
