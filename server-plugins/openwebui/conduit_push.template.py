class Event:
    class Valves(BaseModel):
        allow_private_endpoints: bool = Field(
            default=False,
            description=(
                "Allow push endpoints on private, local or loopback addresses, such as a "
                "UnifiedPush distributor on your LAN. Leave off unless you need it."
            ),
        )
        extra_allowed_hosts: str = Field(
            default="",
            description="Comma-separated host names that skip the private-address check, e.g. ntfy.home.arpa.",
        )
        max_subscriptions_per_user: int = Field(
            default=10, ge=1, le=100, description="How many devices each user can register."
        )
        timeout_s: float = Field(default=5, gt=0, le=60, description="Seconds to wait for each push endpoint.")
        max_channel_recipients: int = Field(
            default=500,
            ge=0,
            le=10000,
            description="The most people one channel message notifies. 0 turns channel notifications off.",
        )

    class UserValves(BaseModel):
        subscriptions: str = Field(default="[]", description="Managed by Conduit. Do not edit.")
        status: str = Field(default="{}", description="Delivery status for Conduit. Do not edit.")

    def __init__(self):
        self.valves = self.Valves()
        self._tasks: Set[asyncio.Task] = set()
        self._loop: Any = None
        self._semaphore: Any = None
        self._locks: Any = weakref.WeakValueDictionary()
        self._nonces: "OrderedDict[str, bool]" = OrderedDict()
        self._ssrf_cache: "OrderedDict[str, Tuple[bool, float]]" = OrderedDict()
        self._warned: Set[str] = set()

    async def event(self, event, __event_name__=None, __request__=None, __id__=None, **kwargs):
        """Called by Open WebUI for every event. Returns at once; sends run in the background."""
        try:
            self._dispatch(event, __event_name__, __request__, __id__)
        except Exception as error:
            log.warning("conduit push: could not handle an event (%s)", type(error).__name__)

    def _dispatch(self, event: Any, name: Any, request: Any, function_id: Any) -> None:
        if not isinstance(event, dict):
            return
        name = name or event.get("event")
        if name not in ("chat.finished", "chat.failed", "message.created", "function.valves_updated"):
            return
        function_id = function_id or (__name__[len("function_"):] if __name__.startswith("function_") else "conduit_push")
        data = event.get("data") if isinstance(event.get("data"), dict) else {}
        actor = event.get("actor") if isinstance(event.get("actor"), dict) else {}
        subject = event.get("subject") if isinstance(event.get("subject"), dict) else {}
        valves = self.valves
        self._bind_loop()

        if name in ("chat.finished", "chat.failed"):
            self._spawn("reply", self._on_chat(function_id, name, data, _from_conduit(request), valves))
        elif name == "message.created":
            if data.get("channel_id") and _text(subject.get("id")):
                self._spawn("channel", self._on_channel(function_id, data, actor, subject["id"], valves))
        elif subject.get("id") == function_id and data.get("scope") == "user" and _text(actor.get("id")):
            self._spawn("subscribe", self._on_valves_updated(function_id, actor["id"], valves))

    def _bind_loop(self) -> None:
        loop = asyncio.get_running_loop()
        if self._loop is not loop:
            self._loop = loop
            self._semaphore = asyncio.Semaphore(SEND_CONCURRENCY)
            self._locks = weakref.WeakValueDictionary()

    def _spawn(self, label: str, job: Any) -> None:
        if len(self._tasks) >= MAX_PENDING_JOBS:
            job.close()
            log.warning("conduit push: too many notifications in flight, dropped one")
            return
        task = asyncio.ensure_future(self._guard(label, job))
        self._tasks.add(task)
        task.add_done_callback(self._tasks.discard)

    async def _guard(self, label: str, job: Any) -> None:
        try:
            await job
        except asyncio.CancelledError:
            raise
        except Exception as error:
            log.warning("conduit push: %s failed (%s)", label, type(error).__name__)

    async def _wait_idle(self) -> None:
        """Waits for every notification in flight. Used by tests."""
        while self._tasks:
            await asyncio.gather(*list(self._tasks), return_exceptions=True)

    def _warn_once(self, key: str, message: str) -> None:
        if key not in self._warned:
            self._warned.add(key)
            log.warning(message)

    def _user_lock(self, user_id: str) -> asyncio.Lock:
        lock = self._locks.get(user_id)
        if lock is None:
            lock = asyncio.Lock()
            self._locks[user_id] = lock
        return lock

    def _claim_nonce(self, user_id: str, sid: str, nonce: str) -> bool:
        key = user_id + "|" + sid + "|" + nonce
        if key in self._nonces:
            return False
        self._nonces[key] = True
        while len(self._nonces) > NONCE_MEMORY:
            self._nonces.popitem(last=False)
        return True

    # Events

    async def _on_chat(self, function_id: str, name: str, data: Dict[str, Any], from_conduit: bool, valves: Any) -> None:
        user_id, chat_id, message_id = (_text(data.get(k)) for k in ("user_id", "chat_id", "message_id"))
        if not (user_id and chat_id and message_id):
            return
        kind = "reply" if name == "chat.finished" else "reply_failed"
        stored = await _read_user_valves(function_id, user_id)
        targets = [
            sub
            for sub in self._usable(stored, valves)
            if kind in sub.events and (sub.origin == "any" or from_conduit)
        ]
        if not targets:
            return
        if kind == "reply":
            title, body = _text(data.get("title")), _preview(data.get("message"))
        else:
            title, body = await self._chat_title(chat_id), ""
        note = cp.build(
            kind,
            SOURCE,
            ids={"chat": chat_id, "msg": message_id},
            title=title,
            body=body,
            dedup_key="chat:" + chat_id + ":" + message_id,
            group="chat:" + chat_id,
            clean=False,
        )
        await self._deliver(function_id, {user_id: [(sub, note) for sub in targets]}, valves)

    async def _on_channel(
        self, function_id: str, data: Dict[str, Any], actor: Dict[str, Any], message_id: str, valves: Any
    ) -> None:
        limit = int(valves.max_channel_recipients)
        if limit <= 0:
            return
        from open_webui.models.channels import Channels
        from open_webui.models.messages import Messages

        channel_id = _text(data.get("channel_id"))
        try:
            message = await Messages.get_message_by_id(message_id, include_thread_replies=False)
        except TypeError:
            message = await Messages.get_message_by_id(message_id)
        if message is None or _attr(message, "channel_id") != channel_id:
            return
        if _attr(message, "parent_id"):
            return  # Thread replies don't notify.
        channel = await Channels.get_channel_by_id(channel_id)
        if channel is None or _attr(channel, "deleted_at") or _attr(channel, "archived_at"):
            return

        members = await Channels.get_members_by_channel_id(channel_id) or []
        recipients = list(
            dict.fromkeys(
                _text(_attr(m, "user_id")) for m in members if not _attr(m, "is_channel_muted")
            )
        )
        kind = _attr(channel, "type")
        if kind not in ("dm", "group"):
            # Standard channels: members who still have read access, as Open WebUI's
            # own channel notifications do. Group and DM access is membership.
            allowed = await self._read_access(channel)
            if allowed is None:
                return  # Membership alone doesn't prove read access.
            recipients = [uid for uid in recipients if uid in allowed]
        sender_id = None if actor.get("type") == "webhook" else (_text(actor.get("id")) or _text(_attr(message, "user_id")))
        recipients = [uid for uid in recipients if uid and uid != sender_id][:limit]
        if not recipients:
            return

        sender = _text(actor.get("name")) or _text(_attr(_attr(message, "user"), "name"))
        channel_name = _text(_attr(channel, "name"))
        title = sender if kind == "dm" or not channel_name else "#" + channel_name
        note = cp.build(
            "channel",
            SOURCE,
            ids={"channel": channel_id, "msg": message_id},
            title=title,
            body=_preview(_attr(message, "content") or data.get("content_preview")),
            author=sender or None,
            dedup_key="channel:" + channel_id + ":" + message_id,
            group="channel:" + channel_id,
            clean=False,
        )
        stored = await self._read_many_user_valves(function_id, recipients)
        work = {}
        for uid in recipients:
            jobs = [(sub, note) for sub in self._usable(stored.get(uid), valves) if "channel" in sub.events]
            if jobs:
                work[uid] = jobs
        if work:
            await self._deliver(function_id, work, valves)

    async def _on_valves_updated(self, function_id: str, user_id: str, valves: Any) -> None:
        """A user saved this function's valves, normally Conduit subscribing a device."""
        stored = await _read_user_valves(function_id, user_id)
        if stored is None:
            return
        raw_list = _parse_list(stored.get("subscriptions"))
        if raw_list is None:
            return
        status = _parse_dict(stored.get("status"))
        now = int(time.time())
        subs, _, invalid = _select(raw_list, now, valves.max_subscriptions_per_user)
        notes = {sid: {"code": None, "at": now, "err": "invalid"} for sid in invalid}
        jobs = []
        for sub in subs:
            pending = sub.nonce and not (sub.test_at and now - sub.test_at > TEST_MAX_AGE_S)
            handled = _attr(status.get(sub.sid), "nonce") == sub.nonce
            if pending and not handled:
                if self._claim_nonce(user_id, sub.sid, sub.nonce):
                    test = cp.build(
                        "test", SOURCE, ids={}, title="", body="", dedup_key="test:" + sub.nonce, nonce=sub.nonce
                    )
                    jobs.append((sub, test))
            elif not self._trusted(sub, valves) and not await self._endpoint_is_public(sub.endpoint):
                notes[sub.sid] = {"code": None, "at": now, "err": "blocked"}
        await self._deliver(function_id, {user_id: jobs}, valves, notes={user_id: notes})

    # Loading

    def _usable(self, stored: Optional[Dict[str, Any]], valves: Any) -> List[_Subscription]:
        if not isinstance(stored, dict):
            return []
        raw_list = _parse_list(stored.get("subscriptions"))
        if not raw_list:
            return []
        return _select(raw_list, int(time.time()), valves.max_subscriptions_per_user)[0]

    async def _chat_title(self, chat_id: str) -> str:
        try:
            from open_webui.models.chats import Chats

            return _text(await Chats.get_chat_title_by_id(chat_id))
        except Exception:
            return ""

    async def _read_access(self, channel: Any) -> Optional[Set[str]]:
        """Ids of users with read access, or None when Open WebUI has no such helper."""
        try:
            from open_webui.routers.channels import get_channel_users_with_access
        except Exception:
            self._warn_once("access", "conduit push: channel access helper missing, standard channels won't notify")
            return None
        users = await get_channel_users_with_access(channel, "read")
        return {_text(_attr(user, "id")) for user in users or []}

    async def _read_many_user_valves(self, function_id: str, user_ids: List[str]) -> Dict[str, Dict[str, Any]]:
        """Every recipient's valves for this function, in one query when possible."""
        try:
            from open_webui.models.users import Users

            users = await Users.get_users_by_user_ids(list(user_ids))
        except Exception:
            users = None
        try:
            from open_webui.utils.valves import decrypt_valves
        except Exception:
            decrypt_valves = None

        found: Dict[str, Dict[str, Any]] = {}
        slow: List[str] = list(user_ids) if users is None else []
        for user in users or []:
            settings = _attr(user, "settings")
            if hasattr(settings, "model_dump"):
                settings = settings.model_dump()
            functions = settings.get("functions") if isinstance(settings, dict) else None
            valve_map = functions.get("valves") if isinstance(functions, dict) else None
            stored = valve_map.get(function_id) if isinstance(valve_map, dict) else None
            if isinstance(stored, str) and stored:
                if decrypt_valves is None:
                    slow.append(_text(_attr(user, "id")))
                    continue
                stored = decrypt_valves(stored)
            if isinstance(stored, dict) and stored:
                found[_text(_attr(user, "id"))] = stored
        for user_id in slow:
            stored = await _read_user_valves(function_id, user_id)
            if stored:
                found[user_id] = stored
        return found

    # Sending

    def _trusted(self, sub: _Subscription, valves: Any) -> bool:
        return bool(valves.allow_private_endpoints) or sub.host in _allowed_hosts(valves.extra_allowed_hosts)

    async def _endpoint_is_public(self, url: str) -> bool:
        now = time.monotonic()
        cached = self._ssrf_cache.get(url)
        if cached is not None and cached[1] > now:
            return cached[0]
        allowed = await asyncio.to_thread(_check_public_endpoint, url)
        self._ssrf_cache[url] = (allowed, now + (SSRF_OK_TTL_S if allowed else SSRF_BLOCKED_TTL_S))
        self._ssrf_cache.move_to_end(url)
        while len(self._ssrf_cache) > SSRF_CACHE_SIZE:
            self._ssrf_cache.popitem(last=False)
        return allowed

    async def _deliver(
        self,
        function_id: str,
        work: Dict[str, List[Tuple[_Subscription, Dict[str, Any]]]],
        valves: Any,
        notes: Optional[Dict[str, Dict[str, Dict[str, Any]]]] = None,
    ) -> None:
        sessions = _Sessions()
        try:
            results = await asyncio.gather(
                *(
                    self._deliver_user(function_id, user_id, jobs, valves, sessions, (notes or {}).get(user_id))
                    for user_id, jobs in work.items()
                ),
                return_exceptions=True,
            )
        finally:
            await sessions.close()
        for result in results:
            if isinstance(result, Exception):
                log.warning("conduit push: delivery failed (%s)", type(result).__name__)

    async def _deliver_user(
        self,
        function_id: str,
        user_id: str,
        jobs: List[Tuple[_Subscription, Dict[str, Any]]],
        valves: Any,
        sessions: _Sessions,
        notes: Optional[Dict[str, Dict[str, Any]]],
    ) -> None:
        results = await asyncio.gather(*(self._send(sessions, sub, note, valves) for sub, note in jobs))
        now = int(time.time())
        statuses = dict(notes or {})
        dead: Set[Tuple[str, str]] = set()
        for (sub, note), (code, err) in zip(jobs, results):
            entry = {"code": code, "at": now, "err": err}
            if note.get("k") == "test":
                entry["nonce"] = note.get("n")
            statuses[sub.sid] = entry
            if err == "gone":
                dead.add((sub.sid, sub.endpoint))
        failed = sum(1 for _, err in results if err)
        if failed:
            log.info("conduit push: %d of %d sends failed", failed, len(results))
        await self._commit(function_id, user_id, valves, statuses, dead)

    async def _send(
        self, sessions: _Sessions, sub: _Subscription, note: Dict[str, Any], valves: Any
    ) -> Tuple[Optional[int], Optional[str]]:
        """Encrypts and posts one notification. Returns (HTTP status, error category)."""
        async with self._semaphore:
            try:
                trusted = self._trusted(sub, valves)
                if not trusted and not await self._endpoint_is_public(sub.endpoint):
                    return None, "blocked"
                try:
                    body = cp.seal(note, {"p256dh": sub.p256dh, "auth": sub.auth})
                except Exception:
                    return None, "encrypt"
                headers = webpush.headers(note["k"], sub.auth_bytes, note["dk"])
                status = await _post(sessions.get(trusted), sub.endpoint, body, headers, valves.timeout_s)
            except asyncio.CancelledError:
                raise
            except asyncio.TimeoutError:
                return None, "timeout"
            except ValueError:
                return None, "blocked"  # The connector refused an address that isn't public.
            except Exception:
                return None, "network"
            return status, _classify(status)

    async def _commit(
        self,
        function_id: str,
        user_id: str,
        valves: Any,
        statuses: Dict[str, Dict[str, Any]],
        dead: Set[Tuple[str, str]],
    ) -> None:
        """Records delivery status and prunes dead or stale subscriptions.

        Under a per-user lock it works the change out on one read of the
        valves. If anything changes, it reads them again just before writing
        and applies the change to that fresh copy, reusing the first pass's
        parsing, so a device that subscribed meanwhile is kept and the gap
        between the read that is written back and the write is as short as it
        can be.

        It can't close that gap. The lock only orders this worker's commits,
        and Open WebUI has no compare-and-set, so a write that lands inside it
        is overwritten: from another worker, or from the app saving the valves
        over REST, for example a device subscribing.

        Writes go through the model method, which doesn't publish an event, so
        nothing loops.
        """
        from open_webui.models.functions import Functions

        now = int(time.time())
        cap = valves.max_subscriptions_per_user
        parse = _ParseCache()
        async with self._user_lock(user_id):
            stored = await _read_user_valves(function_id, user_id)
            if stored is None or not _merge_commit(stored, now, cap, statuses, dead, parse):
                return
            fresh = await _read_user_valves(function_id, user_id)
            if fresh is None or not _merge_commit(fresh, now, cap, statuses, dead, parse):
                return
            await Functions.update_user_valves_by_id_and_user_id(function_id, user_id, fresh)
