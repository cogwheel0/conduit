def _load_webpush_library():
    """Loads the inlined library as private modules, so its own relative imports work."""
    package_name = __name__ + "._conduit_webpush"
    package = types.ModuleType(package_name)
    package.__path__ = []
    package.__package__ = package_name
    sys.modules[package_name] = package
    for name in ("webpush", "payload"):
        module = types.ModuleType(package_name + "." + name)
        module.__package__ = package_name
        module.__file__ = "<conduit_webpush/" + name + ".py>"
        sys.modules[module.__name__] = module
        exec(compile(_CONDUIT_WEBPUSH_SOURCES[name], module.__file__, "exec"), module.__dict__)
        setattr(package, name, module)
    return package.webpush, package.payload


