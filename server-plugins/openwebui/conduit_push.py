# Conduit Push for Open WebUI
#
# Sends Conduit push notifications when a reply finishes or fails, and when
# someone posts in a channel. Every notification is encrypted here, on this
# server, to the receiving device's own P-256 key (Web Push, RFC 8291). It is
# then posted to that device's push endpoint: either the Conduit relay, which
# forwards the ciphertext to Apple or Google, or the user's own UnifiedPush
# distributor. Nothing between this server and the device can read it.
#
# Users register their devices from the Conduit app. Each device's
# subscription is stored in this function's user valves, which Conduit
# manages; nobody needs to edit them by hand.
#
# Protocol: docs/push/PROTOCOL.md in the Conduit repository.
# Admin guide: docs/push/ADMIN_SETUP.md in the same repository.
#
# The released conduit_push.py is generated by server-plugins/openwebui/build.py
# from conduit_push.template.py and the shared server-plugins/common/conduit_webpush
# library. Edit those two, then run the build.

