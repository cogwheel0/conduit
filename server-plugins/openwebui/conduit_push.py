def _b64u_bytes(value: Any, size: int) -> Optional[bytes]:
    if not isinstance(value, str) or not _B64U.match(value):
        return None
    try:
        raw = webpush.b64u_decode(value)
    except ValueError:
        return None
    return raw if len(raw) == size else None


def _is_sid(value: Any) -> bool:
    return isinstance(value, str) and bool(_SID.match(value)) and _b64u_bytes(value, 16) is not None


def _is_p256_point(raw: Optional[bytes]) -> bool:
    if raw is None or raw[0] != 0x04:
        return False
    try:
        ec.EllipticCurvePublicKey.from_encoded_point(ec.SECP256R1(), raw)
    except (ValueError, TypeError):
        return False
    return True


def _endpoint_host(value: Any) -> Optional[str]:
    """The host of a well-formed https endpoint, or None."""
    if not isinstance(value, str) or not 8 < len(value) <= 2048 or not value.isascii():
        return None
    if any(ch in value for ch in "\\ ") or any(ord(ch) < 0x21 or ord(ch) == 0x7F for ch in value):
        return None
    try:
        parts = urllib.parse.urlsplit(value)
        parts.port  # Raises on a malformed port.
    except ValueError:
        return None
    if parts.scheme != "https" or not parts.hostname or "@" in parts.netloc:
        return None
    return parts.hostname.lower()


def _parse_subscription(raw: Any) -> Tuple[str, Optional[_Subscription]]:
    """Returns ("ok", subscription), ("unsupported", None) or ("invalid", None).

    An entry for a newer protocol is unsupported: it is kept but not used.
    """
    if not isinstance(raw, dict):
        return "invalid", None
    proto = raw.get("proto", PROTOCOL)
    if isinstance(proto, bool) or not isinstance(proto, int) or proto < 1:
        return "invalid", None
    if proto > PROTOCOL:
        return "unsupported", None
    sid = raw.get("sid")
    host = _endpoint_host(raw.get("endpoint"))
    p256dh = _b64u_bytes(raw.get("p256dh"), 65)
    auth = _b64u_bytes(raw.get("auth"), 16)
    if not _is_sid(sid) or host is None or auth is None or not _is_p256_point(p256dh):
        return "invalid", None

    did = raw.get("did")
    if not isinstance(did, str) or not 0 < len(did) <= 128:
        did = sid
    events = raw.get("events")
    events = tuple(e for e in events if isinstance(e, str)) if isinstance(events, list) else DEFAULT_EVENTS
    test = raw.get("test") if isinstance(raw.get("test"), dict) else {}
    nonce = test.get("nonce")
    return "ok", _Subscription(
        sid=sid,
        did=did,
        endpoint=raw["endpoint"],
        host=host,
        p256dh=raw["p256dh"],
        auth=raw["auth"],
        auth_bytes=auth,
        events=events,
        origin="any" if raw.get("origin") == "any" else "conduit",
        seen=_int(raw.get("seen")),
        nonce=nonce if isinstance(nonce, str) and _NONCE.match(nonce) else None,
        test_at=_int(test.get("at")),
    )


def _select(raw_list: List[Any], now: int, cap: int) -> Tuple[List[_Subscription], Set[int], List[str]]:
    """Normalizes a stored subscription list.

    Drops malformed entries and entries not seen for 30 days, keeps the newest
    entry per device (`did`) and per `sid`, and keeps at most `cap` entries,
    newest first. Returns the usable subscriptions in stored order, the indexes
    of the stored entries to keep, and the sids of malformed entries.
    """
    keep: Set[int] = set()
    invalid: List[str] = []
    fresh: List[Tuple[int, _Subscription]] = []
    for index, raw in enumerate(raw_list):
        state, sub = _parse_subscription(raw)
        if state == "unsupported":
            keep.add(index)
        elif state == "invalid":
            sid = raw.get("sid") if isinstance(raw, dict) else None
            if _is_sid(sid):
                invalid.append(sid)
        elif now - sub.seen <= STALE_AFTER_S:
            fresh.append((index, sub))

    def newest(pairs, key):
        best: Dict[str, Tuple[int, _Subscription]] = {}
        for index, sub in pairs:
            current = best.get(key(sub))
            if current is None or (sub.seen, index) >= (current[1].seen, current[0]):
                best[key(sub)] = (index, sub)
        return list(best.values())

    chosen = newest(newest(fresh, lambda s: s.did), lambda s: s.sid)
    chosen.sort(key=lambda pair: (pair[1].seen, pair[0]), reverse=True)
    chosen = sorted(chosen[: max(int(cap), 1)], key=lambda pair: pair[0])
    keep.update(index for index, _ in chosen)
    return [sub for _, sub in chosen], keep, invalid


def _strip_hidden(text: str) -> str:
    """Drops reasoning and tool blocks, including one cut off before its end."""
    kept: List[str] = []
    depth = 0
    position = 0
    for match in _HIDDEN.finditer(text):
        if depth == 0:
            kept.append(text[position:match.start()])
        closing = bool(match.group(1)) or match.group(3) == "end" or bool(match.group(4))
        depth = max(depth - 1, 0) if closing else depth + 1
        position = match.end()
    if depth == 0:
        kept.append(text[position:])
    return _SOLUTION_MARKER.sub(" ", " ".join(kept))


def _preview(raw: Any) -> str:
    """Plain-text preview of an event's Markdown text."""
    text = _text(raw)
    truncated = len(text) == EVENT_TEXT_LIMIT + 3 and text.endswith("...")
    if truncated:
        text = text[:EVENT_TEXT_LIMIT]
    text = _MENTION.sub(lambda m: m.group(1) + (m.group(3) or m.group(2)), text)
    text = cp.clean_text(_strip_hidden(text))
    return text + cp.ELLIPSIS if truncated and text else text


def _classify(status: int) -> Optional[str]:
    if 200 <= status < 300:
        return None
    if status in (404, 410):
        return "gone"
    if status == 413:
        return "too_large"
    if status == 429:
        return "rate_limited"
    if status >= 500:
        return "server_error"
    return "rejected"


